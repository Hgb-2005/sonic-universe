'use strict';
const fs=require('node:fs');
const path=require('node:path');
const esbuild=require('esbuild');

const root=path.resolve(__dirname,'../..');
const output=path.join(root,'outputs','local-file-tags.js');
const {metafile}=esbuild.buildSync({
  absWorkingDir:__dirname,entryPoints:['entry.mjs'],outfile:output,
  platform:'browser',bundle:true,format:'iife',target:'es2022',minify:true,metafile:true,
  banner:{js:'/* Generated by scripts/local-metadata/build.cjs. See assets/local-file-tags-notices.txt. */'},
});

const notices=new Map();
for (const input of Object.keys(metafile.inputs)) {
  if (!input.includes('node_modules')) continue;
  let dir=path.dirname(fs.realpathSync(path.resolve(__dirname,input)));
  for (;;) {
    const file=path.join(dir,'package.json');
    if (fs.existsSync(file)) {
      const pkg=JSON.parse(fs.readFileSync(file,'utf8'));
      if (pkg.name&&pkg.version) {
        const key=pkg.name+'@'+pkg.version;
        if (!notices.has(key)) {
          const license=fs.readdirSync(dir).find(name=>/^(?:licen[cs]e|copying)(?:\.(?:txt|md))?$/i.test(name));
          if (!license) throw new Error('Missing license text for '+key);
          notices.set(key,fs.readFileSync(path.join(dir,license),'utf8').trim());
        }
        break;
      }
    }
    const parent=path.dirname(dir);
    if (parent===dir) throw new Error('Package metadata missing for '+input);
    dir=parent;
  }
}
const content=[...notices].sort(([left],[right])=>left.localeCompare(right)).map(([name,license])=>name+'\n\n'+license).join('\n\n----------------------------------------\n\n');
fs.writeFileSync(path.join(root,'outputs','assets','local-file-tags-notices.txt'),content+'\n');
